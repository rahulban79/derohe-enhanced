package gsplit

import (
	"encoding/json"
	"os"
	"path/filepath"
	"testing"
)

// Round 30 (rft §7 B239, memory control): the POSIX shm each split geometry maps, as a golden file the harness's
// shm-budget preflight reads (harness/intel/resource_intel.py shm), so the preflight's figure is this layout's and
// never a hand-typed literal. 8192,3,2 needs ~8.8 GB against ~5.9 GB at 4096,4,2 (gpu_split.go). The file also
// carries the layout constants so the preflight can size a geometry the file does not list with the same formula.
// DERO_SHM_GOLDEN_UPDATE=1 rewrites it.
type shmGolden struct {
	Doc        string `json:"_doc"`
	MsgLen     int    `json:"msg_len"`
	DStride    int    `json:"dstride"`
	SStride    int    `json:"sstride_words"`
	Align      int    `json:"align"`
	GPUSHA     bool   `json:"gpu_sha"`
	Geometries []struct {
		Geom  [3]int `json:"geom"`
		Bytes int    `json:"bytes"`
	} `json:"geometries"`
}

var shmGoldenGeoms = [][3]int{{4096, 4, 2}, {8192, 3, 2}, {8192, 4, 2}, {8192, 5, 3}, {16384, 2, 2}}

func TestR30ShmLayoutGolden(t *testing.T) {
	want := shmGolden{Doc: "r30 B239: NewLayout(batch*depth, gpuSHA=true).Size per DERO_GSPLIT geometry; generated by TestR30ShmLayoutGolden (DERO_SHM_GOLDEN_UPDATE=1)",
		MsgLen: MsgLen, DStride: DStride, SStride: SStride, Align: align, GPUSHA: true}
	for _, g := range shmGoldenGeoms {
		want.Geometries = append(want.Geometries, struct {
			Geom  [3]int `json:"geom"`
			Bytes int    `json:"bytes"`
		}{g, NewLayout(g[0]*g[1], true).Size})
	}
	path := filepath.Join("testdata", "shm_layout_r30.json")
	enc, _ := json.MarshalIndent(want, "", " ")
	enc = append(enc, '\n')
	if os.Getenv("DERO_SHM_GOLDEN_UPDATE") == "1" {
		if err := os.WriteFile(path, enc, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	got, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("%s: %v (DERO_SHM_GOLDEN_UPDATE=1 writes it)", path, err)
	}
	if string(got) != string(enc) {
		t.Fatalf("%s is stale: the layout changed; re-run with DERO_SHM_GOLDEN_UPDATE=1\nwant:\n%s", path, enc)
	}
	// the documented sizes in gpu_split.go: ~5.9 GB at 4096,4,2 and ~8.8 GB at 8192,3,2
	if s := NewLayout(4096*4, true).Size; s < 5_800_000_000 || s > 6_000_000_000 {
		t.Fatalf("4096,4,2 = %d bytes, the comment says ~5.9 GB", s)
	}
	if s := NewLayout(8192*3, true).Size; s < 8_700_000_000 || s > 8_900_000_000 {
		t.Fatalf("8192,3,2 = %d bytes, the comment says ~8.8 GB", s)
	}
}
