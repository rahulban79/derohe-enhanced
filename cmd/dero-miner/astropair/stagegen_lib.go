package astropair

// The generator logic lives in the package (not only in gen_stage.go) so that TestStageIsCurrent can regenerate
// stage_gen.go from the pow.go in this tree and compare. gen_stage.go is a thin main that calls a copy of it.

import (
	"fmt"
	"strings"
)

const (
	stageFirst = "var step_3 [256]byte"             // first line of stage 1 inside AstroBWTv3
	stageLast  = "data_len := uint32((tries-4)*256" // prefix of the last line of stage 1
)

// Generate returns stage_gen.go for the text of astrobwt/astrobwtv3/pow.go.
func Generate(pow string) (string, error) {
	lines := strings.Split(pow, "\n")
	first, last, fn := -1, -1, -1
	for i, l := range lines {
		t := strings.TrimSpace(l)
		switch {
		case strings.HasPrefix(t, "func AstroBWTv3(input []byte) (outputhash [32]byte) {"):
			fn = i
		case fn >= 0 && first < 0 && t == stageFirst:
			first = i
		case first >= 0 && last < 0 && strings.HasPrefix(t, stageLast):
			last = i
		}
	}
	if fn < 0 || first < 0 || last < 0 {
		return "", fmt.Errorf("anchors not found in pow.go (func=%d first=%d last=%d)", fn, first, last)
	}
	body := lines[first : last+1]
	for _, l := range body { // the copy must be straight-line into data_len: nothing may leave the function early
		t := strings.TrimSpace(l)
		if strings.HasPrefix(t, "return") || strings.HasPrefix(t, "defer") || strings.HasPrefix(t, "goto") {
			return "", fmt.Errorf("unexpected control flow in stage 1: %q", t)
		}
	}
	var b strings.Builder
	b.WriteString("// Code generated by gen_stage.go from astrobwt/astrobwtv3/pow.go; DO NOT EDIT.\n")
	fmt.Fprintf(&b, "// Source lines %d-%d of pow.go (stage 1 of AstroBWTv3), copied verbatim except that two identifiers\n", first+1, last+1)
	b.WriteString("// are qualified with the astrobwtv3 package. pow.go is (c) DERO Foundation, see astrobwt/astrobwtv3/LICENSE.txt.\n\n")
	b.WriteString("package astropair\n\n")
	b.WriteString("import (\n\t\"math/bits\"\n\n\t\"github.com/cespare/xxhash\"\n\t\"github.com/dchest/siphash\"\n\t\"github.com/deroproject/derohe/astrobwt/astrobwtv3\"\n\t\"github.com/minio/sha256-simd\"\n\t\"github.com/segmentio/fasthash/fnv1a\"\n\t\"golang.org/x/crypto/salsa20/salsa\"\n)\n\n")
	b.WriteString("// stage1 fills scratch.data[:data_len] exactly as AstroBWTv3 does before its suffix sort.\n")
	b.WriteString("func stage1(input []byte, scratch *lane) uint32 {\n")
	r := strings.NewReplacer("NewCipher(", "astrobwtv3.NewCipher(", "GpuIterHook", "astrobwtv3.GpuIterHook")
	for _, l := range body {
		b.WriteString(r.Replace(l))
		b.WriteString("\n")
	}
	b.WriteString("\treturn data_len\n}\n")
	return b.String(), nil
}
