//go:build ignore

// gen_sha.go writes sha_arm64.s from the Go toolchain's own SHA-256 block function,
// $GOROOT/src/crypto/internal/fips140/sha256/sha256block_arm64.s (BSD-3, The Go Authors; see LICENSE-GO).
// It parses that file's block loop into its sixteen 4-round groups and emits:
//
//	block1: the loop unchanged, one lane, counting blocks instead of bytes;
//	block2: two independent lanes, A in V0-V9 and B in V10-V19, their instructions alternated so the SHA unit
//	        always has a second dependency chain to issue from. The round constants move to V20-V31, so K32..K63
//	        are reloaded into V28-V31 twice per block (12 registers hold 48 of the 64 constants at a time).
//
//	go run gen_sha.go    (writes sha_arm64.s, or $GEN_SHA_OUT; TestAsmIsCurrent uses the latter)
package main

import (
	"fmt"
	"os"
	"os/exec"
	"regexp"
	"strings"
)

func main() {
	root, err := exec.Command("go", "env", "GOROOT").Output()
	if err != nil {
		panic(err)
	}
	path := strings.TrimSpace(string(root)) + "/src/crypto/internal/fips140/sha256/sha256block_arm64.s"
	src, err := os.ReadFile(path)
	if err != nil {
		panic(err)
	}
	lines := strings.Split(string(src), "\n")

	// header: the copyright block at the top of the GOROOT file, kept verbatim
	var header []string
	for _, l := range lines {
		if !strings.HasPrefix(l, "//") {
			break
		}
		header = append(header, l)
	}
	if len(header) < 3 || !strings.Contains(header[0], "The Go Authors") {
		panic("unexpected GOROOT header")
	}

	// macro HASHUPDATE body
	var hashupdate []string
	in := false
	for _, l := range lines {
		if strings.HasPrefix(l, "#define HASHUPDATE") {
			in = true
			continue
		}
		if in {
			t := strings.TrimSpace(strings.TrimSuffix(strings.TrimSpace(l), "\\"))
			if t == "" {
				break
			}
			hashupdate = append(hashupdate, t)
		}
	}
	if len(hashupdate) != 3 {
		panic(fmt.Sprintf("HASHUPDATE has %d instructions", len(hashupdate)))
	}

	// block loop: preamble (message load + state copies) and 16 groups separated by blank lines
	var pre []string
	var groups [][]string
	state := 0
	for _, l := range lines {
		t := strings.TrimSpace(l)
		if i := strings.Index(t, "//"); i >= 0 {
			t = strings.TrimSpace(t[:i])
		}
		switch state {
		case 0:
			if t == "blockloop:" {
				state = 1
			}
			continue
		}
		if strings.HasPrefix(t, "SUB") {
			break
		}
		if t == "" {
			if state == 2 && len(groups) > 0 && len(groups[len(groups)-1]) > 0 {
				groups = append(groups, nil)
			}
			continue
		}
		if strings.HasPrefix(t, "VADD") && strings.Contains(t, "V9.S4") && state == 1 {
			state = 2
			groups = append(groups, nil)
		}
		ins := []string{t}
		if t == "HASHUPDATE" {
			ins = hashupdate
		}
		if state == 1 {
			pre = append(pre, ins...)
		} else {
			groups[len(groups)-1] = append(groups[len(groups)-1], ins...)
		}
	}
	if n := len(groups); n > 0 && len(groups[n-1]) == 0 {
		groups = groups[:n-1]
	}
	if len(groups) != 16 || len(pre) != 11 {
		panic(fmt.Sprintf("parsed %d groups, %d preamble instructions", len(groups), len(pre)))
	}
	// the loop's last statements (after the SUB) add the working state back into the hash
	reg := regexp.MustCompile(`\bV(\d+)\b`)
	for g, grp := range groups { // group g must use round constants K[4g..4g+3], held in V(16+g) by the GOROOT code
		if !strings.Contains(grp[0], fmt.Sprintf("V%d.S4", 16+g)) {
			panic(fmt.Sprintf("group %d does not start with its K register: %q", g, grp[0]))
		}
	}

	// lane renaming: state registers V0..V9 -> V(0+base)..V(9+base); constant registers V16..V31 -> kmap
	rename := func(s string, base int, kmap func(int) int) string {
		return reg.ReplaceAllStringFunc(s, func(m string) string {
			var n int
			fmt.Sscanf(m, "V%d", &n)
			if n >= 16 {
				return fmt.Sprintf("V%d", kmap(n-16))
			}
			if n > 9 {
				panic("unexpected register " + m)
			}
			return fmt.Sprintf("V%d", n+base)
		})
	}
	id := func(k int) int { return 16 + k }
	pairK := func(k int) int {
		switch {
		case k < 8:
			return 20 + k
		case k < 12:
			return 28 + k - 8
		default:
			return 28 + k - 12
		}
	}
	msg := func(s string, ptr string) string { return strings.Replace(s, "(R1)", "("+ptr+")", 1) }

	var o []string
	w := func(f string, a ...interface{}) { o = append(o, fmt.Sprintf(f, a...)) }
	o = append(o, header...)
	w("")
	w("// Code generated by gen_sha.go from $GOROOT/src/crypto/internal/fips140/sha256/sha256block_arm64.s; DO NOT EDIT.")
	w("// The round groups, the HASHUPDATE sequence and the message schedule are the GOROOT code's; only the register")
	w("// names, the loop counter and the constant loads differ. See gen_sha.go.")
	w("")
	w("//go:build arm64")
	w("")
	w("#include \"textflag.h\"")
	w("")
	w("// func block1(h *[8]uint32, p *byte, n int)   n >= 1 blocks of 64 bytes")
	w("TEXT ·block1(SB),NOSPLIT,$0-24")
	w("\tMOVD\th+0(FP), R0")
	w("\tMOVD\tp+8(FP), R1")
	w("\tMOVD\tn+16(FP), R3")
	w("\tMOVD\t$·kt+0(SB), R2")
	w("\tVLD1\t(R0), [V0.S4, V1.S4]")
	w("\tVLD1.P\t64(R2), [V16.S4, V17.S4, V18.S4, V19.S4]")
	w("\tVLD1.P\t64(R2), [V20.S4, V21.S4, V22.S4, V23.S4]")
	w("\tVLD1.P\t64(R2), [V24.S4, V25.S4, V26.S4, V27.S4]")
	w("\tVLD1\t(R2), [V28.S4, V29.S4, V30.S4, V31.S4]")
	w("loop1:")
	for _, s := range pre {
		w("\t%s", s)
	}
	for _, grp := range groups {
		for _, s := range grp {
			w("\t%s", rename(s, 0, id))
		}
	}
	w("\tVADD\tV2.S4, V0.S4, V0.S4")
	w("\tVADD\tV3.S4, V1.S4, V1.S4")
	w("\tSUB\t$1, R3, R3")
	w("\tCBNZ\tR3, loop1")
	w("\tVST1\t[V0.S4, V1.S4], (R0)")
	w("\tRET")
	w("")
	w("// func block2(ha, hb *[8]uint32, pa, pb *byte, n int)   n >= 1 blocks of 64 bytes in each lane")
	w("TEXT ·block2(SB),NOSPLIT,$0-40")
	w("\tMOVD\tha+0(FP), R0")
	w("\tMOVD\thb+8(FP), R5")
	w("\tMOVD\tpa+16(FP), R1")
	w("\tMOVD\tpb+24(FP), R6")
	w("\tMOVD\tn+32(FP), R3")
	w("\tMOVD\t$·kt+0(SB), R2")
	w("\tVLD1\t(R0), [V0.S4, V1.S4]")
	w("\tVLD1\t(R5), [V10.S4, V11.S4]")
	w("\tVLD1.P\t64(R2), [V20.S4, V21.S4, V22.S4, V23.S4]")
	w("\tVLD1\t(R2), [V24.S4, V25.S4, V26.S4, V27.S4]")
	w("loop2:")
	w("\tMOVD\t$·kt+128(SB), R4")
	w("\tVLD1.P\t64(R4), [V28.S4, V29.S4, V30.S4, V31.S4]")
	for i := range pre { // preamble: message loads first (both lanes), then copies and byte swaps
		w("\t%s", rename(msg(pre[i], "R1"), 0, pairK))
		w("\t%s", rename(msg(pre[i], "R6"), 10, pairK))
	}
	for g := range groups {
		if g == 12 { // K48..K63 replace K32..K47, whose last use was group 11
			w("\tVLD1\t(R4), [V28.S4, V29.S4, V30.S4, V31.S4]")
		}
		a, b := groups[g], groups[g]
		for i := 0; i < len(a) || i < len(b); i++ {
			if i < len(a) {
				w("\t%s", rename(a[i], 0, pairK))
			}
			if i < len(b) {
				w("\t%s", rename(b[i], 10, pairK))
			}
		}
	}
	w("\tVADD\tV2.S4, V0.S4, V0.S4")
	w("\tVADD\tV3.S4, V1.S4, V1.S4")
	w("\tVADD\tV12.S4, V10.S4, V10.S4")
	w("\tVADD\tV13.S4, V11.S4, V11.S4")
	w("\tSUB\t$1, R3, R3")
	w("\tCBNZ\tR3, loop2")
	w("\tVST1\t[V0.S4, V1.S4], (R0)")
	w("\tVST1\t[V10.S4, V11.S4], (R5)")
	w("\tRET")
	w("")
	if err := os.WriteFile(outPath(), []byte(strings.Join(o, "\n")), 0644); err != nil {
		panic(err)
	}
}

func outPath() string {
	if p := os.Getenv("GEN_SHA_OUT"); p != "" {
		return p
	}
	return "sha_arm64.s"
}
