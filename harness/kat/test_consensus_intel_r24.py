def grades(doc):
    return {d['id']: d for d in doc['detectors']}


def analyse(m, cap):
    R, miss = m.load_rules(ROOT)
    if miss:
        raise RuntimeError(f'rules missing {miss}')
    return m.analyze(cap, R, ROOT)


def ci1(m):
    cap = synth()
    doc = analyse(m, cap)
    g = grades(doc)
    bad = {k: d['grade'] for k, d in g.items() if d['grade'] != 'NORMAL'}
    k = doc['kpis']
    H = cap['headers']
    dts = [b['ts'] - a['ts'] for a, b in zip(H, H[1:])]
    regs = {}
    for h in H:
        for x in h['miners'][:9]:
            regs[x] = regs.get(x, 0) + 1
    tot = sum(regs.values())
    hh = sum((c / tot) ** 2 for c in regs.values())
    srt = sorted(regs.values(), reverse=True)
    nk = next(i for i in range(1, len(srt) + 1) if sum(srt[:i]) * 2 > tot)
    s = sorted(dts)
    p95 = s[int((len(s) - 1) * .95)] + (s[min(len(s) - 1, int((len(s) - 1) * .95) + 1)] - s[int((len(s) - 1) * .95)]) * (((len(s) - 1) * .95) % 1)
    want = {'block_time_mean_s': round(statistics.fmean(dts) / 1000, 3), 'block_time_median_s': round(statistics.median(dts) / 1000, 3),
            'block_time_p95_s': round(p95 / 1000, 3), 'hhi_regular': round(hh, 5), 'nakamoto_regular': nk,
            'top1_regular_share': round(srt[0] / tot, 4), 'difficulty_rule_mismatches': 0, 'window_blocks': N}
    got = {x: k[x] for x in want}
    ok = len(g) == 18 and not bad and got == want and k['difficulty_clamped_steps'] > 0 and k['difficulty_rule_checked'] == N - 2
    return ok, f'non-NORMAL {bad}; kpis {got} want {want}; clamped {k["difficulty_clamped_steps"]}'


def plant_case(det, grade, plant, cite=None):
    def f(m):
        doc = analyse(m, synth(plant=plant))
        d = grades(doc)[det]
        ev = json.dumps(d['evidence'])
        ok = d['grade'] == grade and (cite is None or cite in ev)
        return ok, f"{det} {d['grade']} (want {grade}) value {d['value']} evidence {ev[:200]}"
    return f


