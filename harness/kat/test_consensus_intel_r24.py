def make_root():
    t = Path(tempfile.mkdtemp(prefix='r24cg-'))
    for d in ('config', 'blockchain', 'cmd', 'p2p', 'globals', 'rpc'):
        (t / d).symlink_to(ROOT / d)
    for f in ('miners/mine_consensus.py', 'miners/minelib.py', 'kit/privkit.py'):   # r24: minelib.emit uses privkit
        (t / 'harness' / f).parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(HARNESS / f, t / 'harness' / f)
    (t / 'harness/runtime').mkdir(parents=True)
    return t


def g26_case(m, mutate=None, rowbreak=False):
    t = make_root()
    try:
        doc = analyse(m, synth())
        if mutate:
            mutate(doc)
        m.write_outputs(doc, t / 'harness/runtime', '20990101T000000Z', series=True)
        r = subprocess.run([sys.executable, '-I', str(t / 'harness/miners/mine_consensus.py')], capture_output=True, text=True, timeout=120)
        if r.returncode:
            raise RuntimeError(r.stderr[-300:])
        if rowbreak:
            rp = t / 'harness/model/raw/consensus.json'
            rd = json.loads(rp.read_text())
            rd['rows'][0]['evidence'][0]['quote'] = 'this quote is on no line of any file'
            rp.write_text(json.dumps(rd))
        return m.g26(t)
    finally:
        shutil.rmtree(t, ignore_errors=True)


def ci19(m):
    ok0, d0 = g26_case(m)
    old = (datetime.datetime.now(datetime.timezone.utc) - datetime.timedelta(hours=30)).isoformat(timespec='seconds')
    st, _ = g26_case(m, lambda d: d.update(captured=old))
    sy, _ = g26_case(m, lambda d: d.update(source='synthetic'))
    mi, _ = g26_case(m, lambda d: d.update(detectors=d['detectors'][1:]))
    rb, _ = g26_case(m, rowbreak=True)
    ok = ok0 and not st and not sy and not mi and not rb
    return ok, f'fresh {ok0} ({d0[:120]}); stale {st}; synthetic {sy}; missing detector {mi}; broken row {rb}'


